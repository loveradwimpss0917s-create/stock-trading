-- 3つのSetupは、いずれも自分自身の min_rr=1.5 をコスト後で満たしていなかった。
--
--   breakout_20d   1.8x/3.0x  グロス1.667 → ネット1.400
--   pullback_ma25  1.8x/3.0x  グロス1.667 → ネット1.400
--   reversal_3d    1.0x/1.5x  グロス1.500 → ネット1.083
--
-- 往復コストはRで見ると損切り倍率だけで決まる（2×スリッページ率÷ATR倍率）。
-- 価格にもATRにも依存しない。よって reversal_3d の 1.0x ストップは往復
-- 0.400R を払い続ける構造で、実測グロスが +0.024R だったことを考えれば
-- 勝てないのは選別の問題ではなく算術の問題だった。
--
-- 利確目標を、コスト後に min_rr を満たす水準まで広げる。これは過去の成績に
-- 対するフィッティングではなく、コストという前向きの制約に対する調整である。
-- ただし必要条件を満たしただけで、十分条件ではない：
--
--   * 目標が遠くなれば到達率は下がる。トレードオフは消えていない。
--   * 「広げたから勝てる」ではない。広げなければ勝てないことが確定していた、
--     というだけ。実際に届くかどうかはリプレイが測る。
update setups set target_rule = '{"type": "atr_mult", "mult": 3.5}'
where key in ('breakout_20d', 'pullback_ma25');

update setups set target_rule = '{"type": "atr_mult", "mult": 2.2}'
where key = 'reversal_3d';
